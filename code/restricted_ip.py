# -*- coding: utf-8 -*-
"""
Restricted Integer Program (RIP) from Column Generation Solution
=========================================================================

Loads the patterns saved by column_generation.py and solves the
restricted integer program once, i.e., the RMP with y_p ∈ {0,1},
using a warm start from the LP solution.

Formulation:
    min   sum_p  c_p * y_p
    s.t.  sum_{p: (s,k) ∈ B_p}  y_p  >= 1    ∀ (s,k) ∈ B   [set covering]
          y_p ∈ {0, 1}

Note on set covering (>=) vs set partitioning (=):
    The LP solution may contain fractional variables, which indicates that
    exact set partitioning may not have an integer feasible solution with
    the current patterns unless branch-and-price is used. With >=, feasibility
    is guaranteed and the extra cost is minimized, since Gurobi avoids
    unnecessary redundant selections.

Input:
    results/{dataset_id}/{dataset_id}_cg_solution.csv

Output:
    results/{dataset_id}/{dataset_id}_rip_solution.csv
    results/{dataset_id}/{dataset_id}_rip_summary.csv

Usage:
    python restricted_ip.py DS-1
    python restricted_ip.py DS-1 --time_limit 7200 --mip_gap 0.001
"""

import os
import sys
import time
import argparse
from collections import defaultdict
from datetime import datetime
from typing import Dict, List, Tuple

import pandas as pd

try:
    import gurobipy as gp
    from gurobipy import GRB
except ImportError:
    print("ERROR: Gurobi is not installed. Run: pip install gurobipy")
    sys.exit(1)


# ============================================================================
# LOAD COLUMN GENERATION SOLUTION
# ============================================================================

def load_column_generation_solution(
    dataset_id: str,
    base_dir: str = None,
) -> pd.DataFrame:
    """
    Load the CSV file generated by column_generation.py.

    Expected columns:
        pattern_id, bin_type_id, cost, n_blocks, n_skus,
        total_x, y_value, blocks

    where 'blocks' is a string such as:
        "SKU_k;SKU_k;..."
    """
    if base_dir is None:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        repo_dir = os.path.dirname(script_dir)
        base_dir = os.path.join(repo_dir, "results", dataset_id)

    csv_path = os.path.join(base_dir, f"{dataset_id}_cg_solution.csv")

    if not os.path.exists(csv_path):
        raise FileNotFoundError(
            f"Column generation solution was not found: {csv_path}\n"
            f"Run first: python column_generation.py {dataset_id}"
        )

    solution_df = pd.read_csv(csv_path)

    required_columns = {
        "pattern_id",
        "bin_type_id",
        "cost",
        "y_value",
        "blocks",
    }
    missing_columns = required_columns - set(solution_df.columns)

    if missing_columns:
        raise ValueError(
            f"Missing columns in cg_solution.csv: {missing_columns}"
        )

    print(f"  Column generation solution loaded: {csv_path}")
    print(f"    Patterns: {len(solution_df):,}")
    print(f"    Bin types: {solution_df['bin_type_id'].nunique()}")

    return solution_df


def parse_blocks(blocks_string: str) -> List[Tuple[str, int]]:
    """
    Convert a string such as "SKU1_0;SKU2_3" into:
        [(SKU1, 0), (SKU2, 3)]

    Uses rsplit so SKU identifiers containing underscores are handled correctly.
    """
    if pd.isna(blocks_string) or blocks_string == "":
        return []

    parsed_blocks = []

    for token in blocks_string.split(";"):
        token = token.strip()

        if not token:
            continue

        sku, block_k_string = token.rsplit("_", 1)
        parsed_blocks.append((sku, int(block_k_string)))

    return parsed_blocks


def build_restricted_ip_structures(solution_df: pd.DataFrame) -> Dict:
    """
    Build the data structures needed for the restricted IP.

    Returns:
        data dictionary with:
            patterns        : list of dictionaries containing pattern_id,
                              bin_type_id, cost, blocks, and lp_value
            blocks          : sorted list of all blocks (s, k)
            block_to_pids   : inverse index block -> [pattern_ids]
    """
    patterns = []
    block_to_pattern_ids = defaultdict(list)
    all_blocks = set()

    for _, row in solution_df.iterrows():
        pattern_id = int(row["pattern_id"])
        bin_type_id = row["bin_type_id"]
        cost = float(row["cost"])
        lp_value = float(row["y_value"])
        blocks = parse_blocks(row["blocks"])

        patterns.append({
            "pattern_id": pattern_id,
            "bin_type_id": bin_type_id,
            "cost": cost,
            "blocks": blocks,
            "lp_value": lp_value,
        })

        for block in blocks:
            block_to_pattern_ids[block].append(pattern_id)
            all_blocks.add(block)

    blocks = sorted(all_blocks)

    # Verify coverage
    n_uncovered = sum(
        1
        for block in blocks
        if not block_to_pattern_ids[block]
    )

    if n_uncovered:
        print(f"  ⚠  {n_uncovered} blocks without coverage")
    else:
        print(f"  ✓  All {len(blocks):,} blocks are covered")

    print(f"  Parsed patterns:      {len(patterns):,}")
    print(f"  Unique blocks:        {len(blocks):,}")

    return {
        "patterns": patterns,
        "blocks": blocks,
        "block_to_pattern_ids": dict(block_to_pattern_ids),
    }


# ============================================================================
# SOLVE RESTRICTED INTEGER PROGRAM
# ============================================================================

def solve_restricted_integer_program(
    data: Dict,
    time_limit: float = 3600.0,
    mip_gap: float = 0.001,
    lp_lower_bound: float = None,
) -> Dict:
    """
    Build and solve the Restricted Integer Program using the CG patterns.

    Parameters
    ----------
    data:
        Data structures returned by build_restricted_ip_structures().

    time_limit:
        Time limit in seconds. Default: 1 hour.

    mip_gap:
        Acceptable MIP optimality gap. Default: 0.001 = 0.1%.

    lp_lower_bound:
        LP lower bound used to report the LP-to-IP gap.

    Returns
    -------
    Dictionary with:
        integer_objective,
        objective_bound,
        mip_gap_pct,
        n_bins,
        runtime,
        integer_solution,
        type_counts
    """
    start_time = time.time()

    patterns = data["patterns"]
    blocks = data["blocks"]
    block_to_pattern_ids = data["block_to_pattern_ids"]

    print("\n" + "=" * 70)
    print("BUILDING RESTRICTED INTEGER PROGRAM")
    print("=" * 70)

    # ------------------------------------------------------------------
    # Model
    # ------------------------------------------------------------------
    restricted_ip = gp.Model("RIP")
    restricted_ip.Params.OutputFlag = 1
    restricted_ip.Params.TimeLimit = time_limit
    restricted_ip.Params.MIPGap = mip_gap

    # ------------------------------------------------------------------
    # Variables: y_p ∈ {0,1}, with warm start from LP solution
    # ------------------------------------------------------------------
    y_vars = {}
    n_warm_start_ones = 0

    for pattern in patterns:
        pattern_id = pattern["pattern_id"]
        lp_value = pattern["lp_value"]

        var = restricted_ip.addVar(
            lb=0.0,
            ub=1.0,
            obj=pattern["cost"],
            vtype=GRB.BINARY,
            name=f"y_{pattern_id}",
        )

        # Warm start: patterns with y*_LP ≈ 1 start at 1
        start_value = 1.0 if lp_value > 0.999 else 0.0
        var.Start = start_value

        if start_value == 1.0:
            n_warm_start_ones += 1

        y_vars[pattern_id] = var

    restricted_ip.update()

    print(f"  Binary variables:     {restricted_ip.NumVars:,}")
    print(f"  Warm start y=1:       {n_warm_start_ones:,}")

    # ------------------------------------------------------------------
    # Coverage constraints:
    #     sum_{p: b ∈ B_p} y_p >= 1
    # ------------------------------------------------------------------
    n_blocks_without_pattern = 0

    for block in blocks:
        pattern_ids = block_to_pattern_ids.get(block, [])

        if not pattern_ids:
            n_blocks_without_pattern += 1
            continue

        restricted_ip.addConstr(
            gp.quicksum(y_vars[pattern_id] for pattern_id in pattern_ids) >= 1,
            name=f"cover_{block[0]}_{block[1]}",
        )

    restricted_ip.update()

    print(f"  Constraints:          {restricted_ip.NumConstrs:,}")

    if n_blocks_without_pattern:
        print(
            f"  ⚠  {n_blocks_without_pattern} blocks have no pattern "
            f"→ infeasibility is possible"
        )

    if lp_lower_bound:
        print(f"  LP reference:         {lp_lower_bound:>20,.2f} cm³")

    # ------------------------------------------------------------------
    # Solve
    # ------------------------------------------------------------------
    print("\n" + "-" * 70)
    print("OPTIMIZING RIP")
    print("-" * 70)

    restricted_ip.optimize()
    runtime = time.time() - start_time

    # ------------------------------------------------------------------
    # Extract solution
    # ------------------------------------------------------------------
    print("\n" + "-" * 70)
    print("RESULTS")
    print("-" * 70)

    status = restricted_ip.Status

    if status not in (GRB.OPTIMAL, GRB.TIME_LIMIT):
        print(f"  ✗ RIP was not solved. Status = {status}")
        restricted_ip.dispose()
        return {}

    if restricted_ip.SolCount == 0:
        print("  ✗ No feasible integer solution was found within the time limit.")
        restricted_ip.dispose()
        return {}

    integer_objective = restricted_ip.ObjVal
    objective_bound = restricted_ip.ObjBound
    mip_gap_pct = restricted_ip.MIPGap * 100.0

    integer_solution = {
        pattern_id: var.X
        for pattern_id, var in y_vars.items()
        if var.X > 0.5
    }

    n_bins = len(integer_solution)

    # Used bin types
    type_counts = defaultdict(int)

    for pattern in patterns:
        if pattern["pattern_id"] in integer_solution:
            type_counts[pattern["bin_type_id"]] += 1

    status_text = "OPTIMAL" if status == GRB.OPTIMAL else "TIME LIMIT"

    print(f"  Status:               {status_text}")
    print(f"  z_IP  =  {integer_objective:>25,.2f} cm³")
    print(f"  Bound =  {objective_bound:>25,.2f} cm³")

    if lp_lower_bound and lp_lower_bound > 0:
        lp_to_ip_gap_pct = (
            100.0 * (integer_objective - lp_lower_bound) / lp_lower_bound
        )
        print(f"  z_LP  =  {lp_lower_bound:>25,.2f} cm³")
        print(f"  LP → IP gap:          {lp_to_ip_gap_pct:>19.4f}%")

    print(f"  MIP gap:              {mip_gap_pct:>19.3f}%")
    print(f"  Bins used:            {n_bins:>20,}")
    print(f"  Runtime:              {runtime:>19.2f}s")

    print("\n  Bin distribution by type:")
    for bin_type_id, count in sorted(type_counts.items(), key=lambda item: -item[1]):
        print(f"    {bin_type_id}: {count:,}")

    restricted_ip.dispose()

    return {
        "integer_objective": integer_objective,
        "objective_bound": objective_bound,
        "mip_gap_pct": mip_gap_pct,
        "n_bins": n_bins,
        "runtime": runtime,
        "integer_solution": integer_solution,
        "type_counts": dict(type_counts),
    }


# ============================================================================
# EXPORT RESULTS
# ============================================================================

def save_restricted_ip_results(
    restricted_ip_result: Dict,
    data: Dict,
    dataset_id: str,
    lp_lower_bound: float = None,
    base_dir: str = None,
):
    """Save the restricted IP solution to disk."""
    if base_dir is None:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        repo_dir = os.path.dirname(script_dir)
        base_dir = os.path.join(repo_dir, "results", dataset_id)

    os.makedirs(base_dir, exist_ok=True)

    integer_solution = restricted_ip_result["integer_solution"]
    patterns = data["patterns"]

    pattern_by_id = {
        pattern["pattern_id"]: pattern
        for pattern in patterns
    }

    # --- 1. Detailed integer solution ---
    rows = []

    for pattern_id in integer_solution:
        pattern = pattern_by_id.get(pattern_id)

        if pattern is None:
            continue

        rows.append({
            "pattern_id": pattern_id,
            "bin_type_id": pattern["bin_type_id"],
            "cost": pattern["cost"],
            "n_blocks": len(pattern["blocks"]),
            "blocks": ";".join(
                f"{sku}_{block_k}"
                for sku, block_k in pattern["blocks"]
            ),
        })

    solution_df = pd.DataFrame(rows)

    solution_path = os.path.join(
        base_dir,
        f"{dataset_id}_rip_solution.csv",
    )
    solution_df.to_csv(solution_path, index=False)

    print(f"  ✓ Integer solution: {solution_path}")

    # --- 2. Summary ---
    summary = {
        "dataset_id": dataset_id,
        "n_patterns_rip": len(data["patterns"]),
        "n_blocks": len(data["blocks"]),
        "integer_objective": restricted_ip_result["integer_objective"],
        "objective_bound": restricted_ip_result["objective_bound"],
        "lp_lower_bound": lp_lower_bound if lp_lower_bound else None,
        "mip_gap_pct": restricted_ip_result["mip_gap_pct"],
        "lp_to_ip_gap_pct": (
            100.0
            * (restricted_ip_result["integer_objective"] - lp_lower_bound)
            / lp_lower_bound
            if lp_lower_bound and lp_lower_bound > 0
            else None
        ),
        "n_bins": restricted_ip_result["n_bins"],
        "runtime_s": restricted_ip_result["runtime"],
    }

    summary_df = pd.DataFrame([summary])

    summary_path = os.path.join(
        base_dir,
        f"{dataset_id}_rip_summary.csv",
    )
    summary_df.to_csv(summary_path, index=False)

    print(f"  ✓ Summary:          {summary_path}")


# ============================================================================
# MAIN
# ============================================================================

def main(
    dataset_id: str,
    time_limit: float = 3600.0,
    mip_gap: float = 0.001,
):
    execution_start_time = datetime.now()

    print("=" * 70)
    print(f"RESTRICTED INTEGER PROGRAM (RIP) — {dataset_id.upper()}")
    print("=" * 70)

    # ------------------------------------------------------------------
    # Paths
    # ------------------------------------------------------------------
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_dir = os.path.dirname(script_dir)
    results_dir = os.path.join(repo_dir, "results", dataset_id)

    # ------------------------------------------------------------------
    # 1. Load column generation solution
    # ------------------------------------------------------------------
    print("\n" + "-" * 70)
    print("Loading column generation solution")
    print("-" * 70)

    column_generation_df = load_column_generation_solution(
        dataset_id,
        results_dir,
    )

    # Read LP bound from summary if available
    lp_lower_bound = None

    summary_path = os.path.join(
        results_dir,
        f"{dataset_id}_cg_summary.csv",
    )

    if os.path.exists(summary_path):
        summary_df = pd.read_csv(summary_path)

        # Compatibility with translated and original column_generation.py versions
        if "lower_bound_lp" in summary_df.columns:
            lp_lower_bound = float(summary_df["lower_bound_lp"].iloc[0])
        elif "lb_lp" in summary_df.columns:
            lp_lower_bound = float(summary_df["lb_lp"].iloc[0])

        if lp_lower_bound is not None:
            print(f"  LP bound reference:   {lp_lower_bound:,.2f} cm³")

    # LP solution statistics
    n_integer_like = (column_generation_df["y_value"] > 0.999).sum()

    n_fractional = (
        (column_generation_df["y_value"] > 0.001)
        & (column_generation_df["y_value"] < 0.999)
    ).sum()

    print(f"  Integer-like LP variables:   {n_integer_like:,}")
    print(f"  Fractional LP variables:     {n_fractional:,}")

    # ------------------------------------------------------------------
    # 2. Build structures
    # ------------------------------------------------------------------
    print("\n" + "-" * 70)
    print("Building data structures")
    print("-" * 70)

    data = build_restricted_ip_structures(column_generation_df)

    del column_generation_df

    # ------------------------------------------------------------------
    # 3. Solve RIP
    # ------------------------------------------------------------------
    restricted_ip_result = solve_restricted_integer_program(
        data,
        time_limit=time_limit,
        mip_gap=mip_gap,
        lp_lower_bound=lp_lower_bound,
    )

    if not restricted_ip_result:
        print("\n✗ No solution was obtained. Aborting.")
        return None

    # ------------------------------------------------------------------
    # 4. Save results
    # ------------------------------------------------------------------
    print("\n" + "-" * 70)
    print("Saving results")
    print("-" * 70)

    save_restricted_ip_results(
        restricted_ip_result,
        data,
        dataset_id,
        lp_lower_bound,
        results_dir,
    )

    # ------------------------------------------------------------------
    # Final summary
    # ------------------------------------------------------------------
    total_execution_time = datetime.now() - execution_start_time

    print("\n" + "=" * 70)
    print("EXECUTION COMPLETED")
    print("=" * 70)
    print(f"  Total time:       {total_execution_time}")
    print(
        f"  z_IP:             "
        f"{restricted_ip_result['integer_objective']:>20,.2f} cm³"
    )

    if lp_lower_bound:
        lp_to_ip_gap_pct = (
            100.0
            * (restricted_ip_result["integer_objective"] - lp_lower_bound)
            / lp_lower_bound
        )
        print(f"  z_LP:             {lp_lower_bound:>20,.2f} cm³")
        print(f"  LP → IP gap:      {lp_to_ip_gap_pct:>19.4f}%")

    print(
        f"  MIP gap:          "
        f"{restricted_ip_result['mip_gap_pct']:>19.3f}%"
    )
    print(f"  Bins:             {restricted_ip_result['n_bins']:>20,}")
    print("=" * 70)

    return restricted_ip_result


# ============================================================================
# ENTRY POINT
# ============================================================================

if __name__ == "__main__":
    # --- Defaults for direct execution from Spyder / IDE ---
    DEFAULT_DATASET = "DS-1"
    DEFAULT_TIME_LIMIT = 3600.0   # seconds
    DEFAULT_MIP_GAP = 0.001       # 0.1%

    if len(sys.argv) > 1:
        parser = argparse.ArgumentParser(
            description=(
                "Restricted integer program from a column generation solution"
            )
        )

        parser.add_argument(
            "dataset_id",
            type=str,
            help="Dataset ID, e.g. DS-1",
        )

        parser.add_argument(
            "--time_limit",
            type=float,
            default=DEFAULT_TIME_LIMIT,
            help="Time limit in seconds. Default: 3600",
        )

        parser.add_argument(
            "--mip_gap",
            type=float,
            default=DEFAULT_MIP_GAP,
            help="MIP optimality gap. Default: 0.001 = 0.1%",
        )

        args = parser.parse_args()

        main(
            dataset_id=args.dataset_id,
            time_limit=args.time_limit,
            mip_gap=args.mip_gap,
        )

    else:
        # Execution from Spyder / runfile without arguments
        main(
            dataset_id=DEFAULT_DATASET,
            time_limit=DEFAULT_TIME_LIMIT,
            mip_gap=DEFAULT_MIP_GAP,
        )
